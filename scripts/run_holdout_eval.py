"""Score the platform on seeds it was never tuned on, price the mistakes, and write docs/evaluation.md.

Tuning seeds (1-3) are the ones the thresholds and personas were developed against. Holdout seeds
(1001 and up) are used only here. Offline and free: the rules decide, no model is called.

The cost figures are ASSUMPTIONS for illustration, not bank data. Change COSTS to match a real
institution; the ranking of mistakes (a miss costs far more than a friction) is what matters.
"""

import json
import sys
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend" / "src"))

from nexa.api.sim import SimulationRunner, run_simulation  # noqa: E402

TUNING = [1, 2, 3]
HOLDOUT = list(range(1001, 1009))
COSTS = {"missed_fraud": 5000, "honest_restricted": 200, "honest_case_opened": 15}  # assumed units


def measure(seeds: list[int]) -> dict:  # type: ignore[type-arg]
    """Run all personas over ``seeds`` and add cost, latency and monitor-path shares."""
    doc = run_simulation(SimulationRunner(), seeds)
    s, eps = doc["summary"], doc["episodes"]
    missed = s["fraud_episodes"] - s["fraud_caught"]
    cost = (
        missed * COSTS["missed_fraud"]
        + s["honest_restricted"] * COSTS["honest_restricted"]
        + s["honest_opened"] * COSTS["honest_case_opened"]
    )
    paths = Counter(m["path"] for e in eps for m in e["monitor"])
    total = sum(paths.values()) or 1
    secs = sorted(e["seconds"] for e in eps)
    return {
        "seeds": seeds, "summary": s, "missed_fraud": missed, "cost": cost,
        "cost_per_episode": round(cost / s["episodes"], 1),
        "latency_p50": secs[len(secs) // 2], "latency_max": secs[-1],
        "path_share": {k: round(v / total, 3) for k, v in sorted(paths.items())},
    }  # fmt: skip


def row(name: str, m: dict) -> str:  # type: ignore[type-arg]
    s = m["summary"]
    return (
        f"| {name} | {s['episodes']} | {s['fraud_caught']}/{s['fraud_episodes']} "
        f"| {s['honest_restricted']}/{s['honest_episodes']} | {s['honest_opened']}/{s['honest_episodes']} "
        f"| {m['cost_per_episode']} | {m['latency_p50']} s | {m['path_share']} |"
    )


def main() -> None:
    """Run both sets, write the JSON and the report."""
    tune, hold = measure(TUNING), measure(HOLDOUT)
    drift = max(
        abs(tune["path_share"].get(k, 0) - hold["path_share"].get(k, 0))
        for k in {*tune["path_share"], *hold["path_share"]}
    )
    out = ROOT / "data" / "lab_results" / "holdout.json"
    out.write_text(json.dumps({"tuning": tune, "holdout": hold, "costs": COSTS}, indent=1), "utf-8")
    now = datetime.now(UTC).strftime("%Y-%m-%d")
    report = f"""# Evaluation: tuning seeds versus holdout seeds

Generated by `python scripts/run_holdout_eval.py` on {now}. Rules decide; no model is called.

| Set | Episodes | Fraud caught | Honest restricted | Honest cases opened | Cost per episode | Latency p50 | Monitor paths |
|-----|----------|--------------|-------------------|---------------------|------------------|-------------|---------------|
{row("tuning (seeds 1-3)", tune)}
{row("holdout (seeds 1001-1008)", hold)}

- **Cost model (assumed, not bank data):** a missed fraud {COSTS["missed_fraud"]}, a wrongly restricted honest customer
  {COSTS["honest_restricted"]}, an honest customer's case opened {COSTS["honest_case_opened"]} (analyst time).
- **Drift check:** the largest change in the share of any monitor path between the two sets is
  {drift:.3f}; a jump here on live traffic would mean the mix of payments has moved and thresholds need a look.
- **What this shows:** whether results survive on seeds nobody tuned for. **What it cannot show:** behaviour on
  real customers, or against expert-labelled cases; there are none, and the personas are our own.
- **Reading the paths:** `model_unavailable` means the monitor ran with no model, so those payments were
  decided by the rules alone; with a model on, they split into `routine` and `model`.
- **Finding:** fraud is caught on every holdout episode, but about two in three honest customers still get a
  case opened (analyst friction, not a restriction). That over-escalation, not missed fraud, is the cost driver.
- Red-team tests (prompt injection in memos, channel spoofing, approval replay) run in
  `backend/tests/security` and `backend/tests/unit/agents` on every build.
"""
    (ROOT / "docs" / "evaluation.md").write_text(report, "utf-8", newline="\n")
    print(report)


if __name__ == "__main__":
    main()
