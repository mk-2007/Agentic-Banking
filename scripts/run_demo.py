"""Run the demo end to end through the HTTP API and print (or write) a Markdown report.

    python scripts/run_demo.py                          # print the report
    python scripts/run_demo.py --write docs/demo-report.md

Offline and deterministic (rule-based decisions, no model, no key). It drives the real API in process:
all seven scenarios, the Level 4 two-approver path, a one-role-twice attempt, a rejection and a customer
who is turned away. Exit code is non-zero if any expectation fails.
"""

import argparse
import sys
from pathlib import Path

from fastapi.testclient import TestClient

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend" / "src"))

from nexa.api import CaseService, Principal, create_app  # noqa: E402
from nexa.bank_sim import load_scenarios  # noqa: E402
from nexa.domain.actors import Role  # noqa: E402

TOKENS = {
    "analyst": Principal("ana", Role.FRAUD_ANALYST),
    "risk": Principal("rob", Role.RISK_OFFICER),
    "customer": Principal("carl", Role.CUSTOMER),
}


def main() -> int:
    """Return 0 when every demo expectation held."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", type=Path, help="write the report to this file")
    out_path = parser.parse_args().write

    client = TestClient(create_app(CaseService(), TOKENS))
    h = {k: {"Authorization": f"Bearer {k}"} for k in TOKENS}
    checks: list[tuple[str, bool]] = []

    def check(label: str, ok: bool) -> None:
        checks.append((label, ok))

    def alert(s) -> dict[str, str]:  # noqa: ANN001
        return {
            k: getattr(s.alert, k)
            for k in ("account_id", "customer_id", "transaction_id", "trigger")
        }

    def vote(case_id: str, who: str, verdict: str = "approve"):  # noqa: ANN202
        return client.post(
            f"/cases/{case_id}/votes", json={"verdict": verdict}, headers=h[who]
        )

    lines = [
        "# Demo report",
        "",
        "Generated by `python scripts/run_demo.py` (offline, rule-based decisions, synthetic data). "
        "Each row is a case opened through the real HTTP API.",
        "",
        "## The seven scenarios",
        "",
        "| Scenario | Status | Recommended action | Level | Human approval | Flags |",
        "|---|---|---|---|---|---|",
    ]
    cases = {}
    for s in load_scenarios():
        r = client.post("/cases", json=alert(s), headers=h["analyst"])
        check(f"{s.id} opens (201)", r.status_code == 201)
        c = cases[s.id] = r.json()
        d = c["decision"] or {}
        lines.append(
            f"| {s.title} | `{c['status']}` | `{d.get('recommended_action', '-')}` | {d.get('risk_level', '-')} "
            f"| {'yes' if d.get('approval_required') else 'no'} | {', '.join(c['uncertainty_flags']) or '-'} |"
        )

    f = cases["scenario_f_account_takeover"]
    check("F waits for approval", f["status"] == "waiting_for_approval")
    one = vote(f["id"], "analyst")
    check(
        "F: one approver is not enough", one.json()["status"] == "waiting_for_approval"
    )
    again = vote(f["id"], "analyst")
    check(
        "F: same role twice is refused or still waiting",
        again.status_code == 409 or again.json()["status"] == "waiting_for_approval",
    )
    two = vote(f["id"], "risk")
    check(
        "F: second role executes the freeze (case completed)",
        two.status_code == 200 and two.json()["status"] == "completed",
    )
    replay = vote(f["id"], "risk")
    check("F: replay after execution is refused (409)", replay.status_code == 409)

    b = cases["scenario_b_suspicious"]
    rejected = (
        vote(b["id"], "analyst", "reject")
        if b["status"] == "waiting_for_approval"
        else None
    )
    if rejected is not None:
        check(
            "B: a rejection changes nothing", rejected.json()["status"] != "completed"
        )

    check(
        "customer cannot list cases",
        client.get("/cases", headers=h["customer"]).status_code == 403,
    )
    check("customer cannot vote", vote(f["id"], "customer").status_code == 403)
    check("no token, no access", client.get("/cases").status_code == 401)
    xid = cases["scenario_x_prompt_injection"]["id"]
    memo = (
        client.get(f"/cases/{xid}", headers=h["analyst"]).text
        + client.get(f"/cases/{xid}/audit", headers=h["analyst"]).text
    ).lower()
    check(
        "injection memo text never reaches the response",
        "ignore all previous" not in memo and "system notice" not in memo,
    )

    audit = client.get(f"/cases/{f['id']}/audit", headers=h["analyst"]).json()
    lines += [
        "",
        "## Level 4 path (account takeover)",
        "",
        f"The case needed `{' + '.join(f['approval']['required_roles'])}`. The audit chain has {len(audit)} events:",
        "",
        "```",
        *[
            f"{e['timestamp'][11:19]}  {e['event_type']:<22} {e['actor']:<28} {e['event_hash'][:10]}"
            for e in audit
        ],
        "```",
        "",
        "## What was checked",
        "",
        "| Check | Result |",
        "|---|---|",
        *[f"| {label} | {'pass' if ok else '**FAIL**'} |" for label, ok in checks],
    ]
    report = "\n".join(lines) + "\n"
    if out_path:
        out_path.write_text(report, encoding="utf-8")
    else:
        print(report)
    failed = [label for label, ok in checks if not ok]
    print(
        f"{len(checks) - len(failed)}/{len(checks)} demo checks passed"
        + (f"; failed: {failed}" if failed else "")
    )
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
